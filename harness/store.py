_PINNED = _thread_local()


def backend() -> str:
    """Which store this process talks to: LOCALHARNESS_STORE, else the home's store.json, else SQLite."""
    pinned = getattr(_PINNED, "backend", None)
    if pinned:
        return pinned
    got = (os.environ.get(BACKEND_ENV) or marker().get("backend") or SQLITE).strip().lower()
    return POSTGRES if got == POSTGRES else SQLITE


@contextmanager
def pinned(kind: str):
    """This thread talks `kind` meanwhile: a SQLite copy migrates as SQLite on a Postgres home. #1579."""
    was = getattr(_PINNED, "backend", None)
    _PINNED.backend = kind
    try:
        yield
    finally:
        _PINNED.backend = was


def live() -> bool:
    """Postgres chosen by the default home's store.json rather than by a variable: the deployed services' store."""
    from harness import paths
    if os.environ.get(BACKEND_ENV) or Path(paths.home()).resolve() != Path(paths.DEFAULT_HOME).resolve():
        return False
    return marker().get("backend") == POSTGRES


def dialect(conn) -> str:
    """The dialect of an open connection, whatever the environment says."""
    return POSTGRES if isinstance(conn, PostgresConnection) else SQLITE


def _rewrite(sql: str, rx, repl) -> str:
    """Apply `rx` outside literals and comments only."""
    masked = _MASK.sub(lambda m: "_" * len(m.group(0)), sql)
    out, last = [], 0
    for m in rx.finditer(masked):
        out += [sql[last:m.start()], repl(m) if callable(repl) else repl]
        last = m.end()
    return "".join(out) + sql[last:]


_EMPTY_IN = re.compile(r"\b(NOT\s+)?IN\s*\(\s*\)", re.I)
_IS_PARAM = re.compile(r"\bIS\s+(NOT\s+)?(?=\?)", re.I)
_GLOB = re.compile(r"\bGLOB\s+(\?|:[A-Za-z_]\w*)", re.I)
_CAST_INT = re.compile(r"\bAS\s+INTEGER\b", re.I)
_NAMED = re.compile(r"(?<![:\w]):([A-Za-z_]\w*)")


def dialect_terms(sql: str) -> str:
    """SQLite's `x IN ()`, `x IS ?`, `x GLOB ?` (or `:name`) and 64-bit `CAST(x AS INTEGER)`, as Postgres spells them."""
    sql = _rewrite(sql, _EMPTY_IN, lambda m: "<> ALL('{}')" if m.group(1) else "= ANY('{}')")
    sql = _rewrite(sql, _IS_PARAM, lambda m: "IS DISTINCT FROM " if m.group(1) else "IS NOT DISTINCT FROM ")
    sql = _rewrite(sql, _CAST_INT, "AS BIGINT")
    return _rewrite(sql, _GLOB, lambda m: f"~ sqlite_glob({m.group(1)})")


def named(sql: str) -> str:
    """SQLite's `:name` parameters as psycopg's `%(name)s`, outside literals and comments."""
    return _rewrite(sql, _NAMED, lambda m: f"%({m.group(1)})s")


def placeholders(sql: str) -> str:
    """`?` to `%s`, except where a `?` is not a placeholder.

    THREE CONTEXTS, and the third was found the hard way. A blanket replace
    rewrites question marks inside string literals, which yields a query that
    runs and returns the wrong rows rather than one that raises. It also
    rewrites them inside COMMENTS -- and the comment that exposed this was one
    explaining a different portability bug, which quoted `HAVING times >= ?`
    and so grew a second placeholder for a query with one parameter.

    psycopg counts placeholders before binding, so that one at least fails
    loudly: "the query has 2 placeholders but 1 parameters were passed".
    A literal `%` (LIKE 'a%') is doubled: psycopg reads every `%` as a placeholder's start.
    """
    sql = sql.replace("%", "%%")
    out = []
    i, n = 0, len(sql)
    quote = None
    while i < n:
        ch = sql[i]
        if quote:
            out.append(ch)
            if ch == quote:
                quote = None
            i += 1
        elif ch in "'\"":
            quote = ch
            out.append(ch)
            i += 1
        elif sql.startswith("--", i):
            end = sql.find("\n", i)
            end = n if end == -1 else end
            out.append(sql[i:end])
            i = end
        elif sql.startswith("/*", i):
            end = sql.find("*/", i + 2)
            end = n if end == -1 else end + 2
            out.append(sql[i:end])
            i = end
        elif ch == "?":
            out.append("%s")
            i += 1
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def translate(sql: str) -> str:
    """One SQLite statement, as Postgres would have it.

    Only four things differ, and each is a construct rather than a dialect:
    the placeholder style, `OR IGNORE`, `OR REPLACE`, and where ORDER BY puts NULL.
    """
    if _OR_IGNORE.search(sql):
        sql = _OR_IGNORE.sub("INSERT INTO", sql)
        # No conflict TARGET on purpose: SQLite's OR IGNORE skips a row that
        # violates ANY unique constraint, and naming one column here would
        # quietly stop ignoring the others.
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    m = _OR_REPLACE.search(sql)
    if m:
        table = m.group(1)
        key = _UPSERT_KEYS.get(table)
        if key is None:
            raise ValueError(
                f"INSERT OR REPLACE INTO {table} has no recorded conflict key. "
                f"An upsert must name what it conflicts on; add {table} to "
                f"_UPSERT_KEYS rather than guessing here.")
        listed = [c.strip() for c in (m.group(2) or "").split(",") if c.strip()]
        cols = [c for c in listed if c != key] if listed else _UPSERT_SET[table]
        sql = _OR_REPLACE.sub(lambda mm: f"INSERT INTO {table}" + (f" ({mm.group(2)})" if mm.group(2) else ""), sql)
        assignments = ", ".join(f"{c} = EXCLUDED.{c}" for c in cols)
        sql = (sql.rstrip().rstrip(";")
               + f" ON CONFLICT ({key}) DO UPDATE SET {assignments}")
    if _ALTER_ADD.match(sql):
        for pattern, replacement in (_TYPES[0], _TYPES[3]):
            sql = re.sub(pattern, replacement, sql)
    return placeholders(dialect_terms(null_order(sql)))


_MASK = re.compile(r"'(?:[^']|'')*'|\"[^\"]*\"|--[^\n]*|/\*.*?\*/", re.S)
_ORDER_BY = re.compile(r"\bORDER\s+BY\b", re.I)
_CLAUSE_END = re.compile(r"\b(?:LIMIT|OFFSET|UNION|EXCEPT|INTERSECT|FOR|ROWS|RANGE|GROUPS)\b", re.I)


def null_order(sql: str) -> str:
    """Every ORDER BY term placed as SQLite places NULL: first ascending, last descending (RULE #732)."""
    masked = _MASK.sub(lambda m: "_" * len(m.group(0)), sql)
    inserts = []
    for m in _ORDER_BY.finditer(masked):
        i, depth, start = m.end(), 0, m.end()
        while i <= len(masked):
            ch = masked[i] if i < len(masked) else ";"
            if ch == "(":
                depth += 1
            elif ch == ")" and depth:
                depth -= 1
            elif depth == 0 and (ch in ",);" or _CLAUSE_END.match(masked, i) and not masked[i - 1:i].isalnum()):
                term = masked[start:i]
                if term.strip() and "NULLS" not in term.upper():
                    end = start + len(term.rstrip())
                    inserts.append((end, " NULLS LAST" if re.search(r"\bDESC\s*$", term, re.I) else " NULLS FIRST"))
                if ch != ",":
                    break
                start = i + 1
            i += 1
    for at, text in sorted(inserts, reverse=True):
        sql = sql[:at] + text + sql[at:]
    return sql


#: SQLite's functions the store's queries call, defined for Postgres so the queries stay in one dialect.
COMPAT = r"""
CREATE OR REPLACE FUNCTION instr(text, text) RETURNS integer LANGUAGE sql IMMUTABLE
    AS 'SELECT strpos($1, $2)';
CREATE OR REPLACE FUNCTION json_extract(text, text) RETURNS text LANGUAGE sql IMMUTABLE
    AS 'SELECT ($1::jsonb) #>> string_to_array(substr($2, 3), ''.'')';
CREATE OR REPLACE FUNCTION group_concat_step(text, text) RETURNS text LANGUAGE sql IMMUTABLE STRICT
    AS 'SELECT $1 || '','' || $2';
CREATE OR REPLACE AGGREGATE group_concat(text) (SFUNC = group_concat_step, STYPE = text);
CREATE OR REPLACE FUNCTION sqlite_glob(text) RETURNS text LANGUAGE sql IMMUTABLE
    AS $g$SELECT '^' || replace(replace(replace(regexp_replace($1, '([.^$+(){}|\\])', '\\\1', 'g'),
                                                '*', '.*'), '?', '.'), '[!', '[^') || '$'$g$;
"""


def has_table(conn, name: str) -> bool:
    """Whether the store holds table `name`, asked of whichever backend `conn` is."""
    if dialect(conn) == POSTGRES:
        sql = "SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ?"
    else:
        sql = "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?"
    return conn.execute(sql, (name,)).fetchone() is not None


def statements(script: str) -> list[str]:
    """A script split at its top-level semicolons, skipping those in literals and comments."""
    out, start, i, n, quote = [], 0, 0, len(script), None
    while i < n:
        ch = script[i]
        if quote:
            quote = None if ch == quote else quote
            i += 1
        elif ch in "'\"":
            quote, i = ch, i + 1
        elif script.startswith("--", i):
            end = script.find("\n", i)
            i = n if end == -1 else end
        elif script.startswith("/*", i):
            end = script.find("*/", i + 2)
            i = n if end == -1 else end + 2
        elif ch == ";":
            out.append(script[start:i])
            start = i = i + 1
        else:
            i += 1
    out.append(script[start:])
    return [s.strip() for s in out if _code(s).strip()]


def _code(sql: str) -> str:
    """`sql` without its comments."""
    return re.sub(r"/\*.*?\*/", " ", re.sub(r"--[^\n]*", " ", sql), flags=re.S)


_CREATE_TABLE = re.compile(r"^\s*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)", re.I)
_REFERENCES = re.compile(r"\bREFERENCES\s+(\w+)", re.I)


def _in_dependency_order(stmts: list[str]) -> list[str]:
    """Tables before the tables whose foreign keys name them; Postgres refuses a forward reference."""
    tables = {}
    for s in stmts:
        m = _CREATE_TABLE.match(_code(s))
        if m:
            tables[m.group(1).lower()] = s
    done, out = set(), []

    def place(name, path=()):
        if name in done or name not in tables or name in path:
            return
        for ref in _REFERENCES.findall(_code(tables[name])):
            place(ref.lower(), path + (name,))
        done.add(name)
        out.append(tables[name])

    for s in stmts:
        m = _CREATE_TABLE.match(_code(s))
        if m:
            place(m.group(1).lower())
    return out + [s for s in stmts if not _CREATE_TABLE.match(_code(s))]


def postgres_ddl(sqlite_ddl: str) -> str:
    """DERIVED, never hand-written. Two schemas maintained by hand diverge, and
    the divergence shows up as a column that exists on one backend only."""
    out = sqlite_ddl
    for pattern, replacement in _TYPES:
        out = re.sub(pattern, replacement, out)
    return ";\n".join(_in_dependency_order(statements(out))) + ";\n"


#: `.lastrowid` is a SQLite idea. Postgres returns it, so an INSERT that a
#: caller reads an id from has to ASK, and only a plain INSERT can: one that
#: may do nothing on conflict returns no row.
#: Statements that steer the transaction themselves; a savepoint around one would undo what it means.
_TX_CONTROL = re.compile(r"^\s*(?:SAVEPOINT|RELEASE|ROLLBACK|BEGIN|COMMIT|END)\b", re.I)
_PLAIN_INSERT = re.compile(r"^\s*INSERT\s+INTO\s+(\w+)", re.I)
#: What opens a transaction in sqlite3: a write or an explicit BEGIN, never a read. #1579.
_OPENS = re.compile(r"^\s*(?:INSERT|UPDATE|DELETE|REPLACE|BEGIN)\b", re.I)
_ID_KEY = re.compile(r"\bid\s+INTEGER\s+PRIMARY\s+KEY\b", re.I)
_ID_TABLES: set = set()


def id_tables() -> set:
    """The store's tables keyed by an integer id: only their INSERT can return one."""
    if not _ID_TABLES:
        from harness.memory_store.schema import _DDL
        for stmt in statements(_DDL):
            m = _CREATE_TABLE.match(_code(stmt))
            if m and _ID_KEY.search(_code(stmt)):
                _ID_TABLES.add(m.group(1).lower())
    return _ID_TABLES


class Row:
    """A sqlite3.Row: indexed by position or by case-insensitive column name, iterating its values."""

    __slots__ = ("_keys", "_index", "_values")

    def __init__(self, keys, index, values):
        self._keys, self._index, self._values = keys, index, tuple(values)

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                return self._values[self._index[key.lower()]]
            except KeyError:
                raise IndexError(f"No item with that key: {key!r}") from None
        return self._values[key]

    def keys(self):
        return list(self._keys)

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def __eq__(self, other):
        if isinstance(other, Row):
            return self._keys == other._keys and self._values == other._values
        return NotImplemented

    def __hash__(self):
        return hash((self._keys, self._values))

    def __repr__(self):
        return f"Row({dict(zip(self._keys, self._values))!r})"


def row_factory(cursor):
    """psycopg's hook: every row comes back as a Row, as sqlite3.Row does under SQLite."""
    desc = cursor.description
    if desc is None:
        return tuple
    keys = tuple(c.name for c in desc)
    index = {}
    for i, k in enumerate(keys):
        index.setdefault(k.lower(), i)
    return lambda values: Row(keys, index, values)


class Cursor:
    """The half of a sqlite3.Cursor that harness/memory_store/ uses."""

    def __init__(self, cur, lastrowid=None):
        self._cur = cur
        self.lastrowid = lastrowid

    @property
    def rowcount(self):
        return self._cur.rowcount

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur)


class PostgresConnection:
    """A sqlite3.Connection-shaped view of a psycopg connection.

    Shaped rather than complete: it implements what the 33 statements in
    memory_store actually use. A method nobody calls is a method nobody has
    tested, and this file is small on purpose.
    """

    def __init__(self, conn, pool=None):
        self._conn = conn
        self._opened = False
        # A pooled connection goes back to its pool on close, or when its wrapper is collected unclosed.
        self._release = weakref.finalize(self, _give_back, pool, conn) if pool is not None else None

    def execute(self, sql: str, params=()):
        translated = translate(sql)
        if isinstance(params, dict):
            translated = named(translated)
        plain = _PLAIN_INSERT.match(translated)
        wants_id = (plain and plain.group(1).lower() in id_tables()
                    and "ON CONFLICT" not in translated.upper()
                    and "RETURNING" not in translated.upper())
        if wants_id:
            translated += " RETURNING id"
        cur = self._statement(translated, params if isinstance(params, dict) else tuple(params))
        if wants_id:
            row = cur.fetchone()
            return Cursor(cur, lastrowid=row["id"] if row else None)
        return Cursor(cur)

    def _statement(self, sql, params):
        """One statement undone alone on failure, as SQLite does, and raised as sqlite3's error so callers' excepts hold."""
        import sqlite3
        import psycopg
        from psycopg.pq import TransactionStatus
        cur = self._conn.cursor()
        mark = (self._conn.info.transaction_status == TransactionStatus.INTRANS
                and not _TX_CONTROL.match(sql))
        if mark:
            cur.execute("SAVEPOINT sohot_statement")
        try:
            cur.execute(sql, params)
        except psycopg.Error as exc:
            if mark:
                cur.execute("ROLLBACK TO SAVEPOINT sohot_statement")
            else:
                self._conn.rollback()
            kind = sqlite3.IntegrityError if isinstance(exc, psycopg.IntegrityError) else sqlite3.OperationalError
            raise kind(str(exc)) from exc
        self._opened = self._opened or bool(_OPENS.match(sql))
        if mark:
            cur2 = self._conn.cursor()
            cur2.execute("RELEASE SAVEPOINT sohot_statement")
        return cur

    @property
    def in_transaction(self) -> bool:
        """As sqlite3 reports it: a write or BEGIN is pending, not merely a read psycopg began a transaction for."""
        from psycopg.pq import TransactionStatus
        return self._opened and self._conn.info.transaction_status in (TransactionStatus.INTRANS,
                                                                        TransactionStatus.INERROR)

    def executemany(self, sql: str, rows):
        for row in rows:
            self.execute(sql, row)

    def __enter__(self):
        return self

    def __exit__(self, kind, value, tb):
        if kind is None:
            self.commit()
        else:
            self.rollback()
        return False

    def executescript(self, ddl: str):
        self._conn.cursor().execute(postgres_ddl(ddl) + COMPAT)
        self._conn.commit()

    def commit(self):
        self._conn.commit()
        self._opened = False

    def rollback(self):
        self._conn.rollback()
        self._opened = False

    def close(self):
        if self._release is not None:
            self._release()
        else:
            self._conn.close()


class ScratchConnection(PostgresConnection):
    """Commits never land and close rolls back: the copy a report may write freely. #1579."""

    def commit(self):
        pass

    def close(self):
        self._conn.rollback()
        super().close()


def scratch():
    """This home's Postgres store as the in-memory copy a SQLite home gets: every read, no write kept. #1579."""
    return postgres_connect(cls=ScratchConnection)


def _give_back(pool, conn) -> None:
    try:
        conn.rollback()
    finally:
        pool.putconn(conn)


#: The connections a long-lived service keeps open to the store; a CLI process holds one and needs none. #1507.
POOL_MAX = 8
_POOL: dict = {}


def use_pool(max_size: int = POOL_MAX):
    """From now on this process borrows its Postgres connections from one pool (RULE #119): long-lived services."""
    if "pool" not in _POOL:
        refuse_live(postgres=True)
        import atexit
        from psycopg_pool import ConnectionPool
        import psycopg
        p = ConnectionPool(dsn(), min_size=1, max_size=max_size, open=True, configure=_as_sqlite_binds,
                           kwargs={"row_factory": row_factory, "autocommit": False,
                                   "cursor_factory": psycopg.ClientCursor})
        atexit.register(p.close)
        _POOL["pool"] = p
    return _POOL["pool"]


def drop_pool() -> None:
    p = _POOL.pop("pool", None)
    if p is not None:
        p.close()


def _quoted(value) -> str:
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


