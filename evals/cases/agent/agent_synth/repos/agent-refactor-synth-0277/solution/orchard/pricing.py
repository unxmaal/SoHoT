"""Pricing helpers."""
from orchard import helpers


def running_total(xs):
    """The cumulative sums of xs."""
    out = []
    total = 0
    for x in xs:
        total += x
        out.append(total)
    return out


def dedupe(items):
    """Items with repeats removed, first occurrences kept in order."""
    seen = set()
    out = []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


def quay_row(value, edges):
    """One quay row for the pricing page."""
    return {'quay_row': helpers.bucket(value, edges)}
