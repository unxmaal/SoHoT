"""Tickets helpers."""
from kiln.catalog import is_leap


def truncate_words(text, n):
    """The first n words of text, with ... when words were cut."""
    words = text.split()
    if len(words) <= n:
        return " ".join(words)
    return " ".join(words[:n]) + "..."


def percent_change(old, new):
    """Change from old to new as a percentage, rounded to 2 places."""
    if old == 0:
        raise ValueError("no change from zero")
    return round((new - old) / old * 100, 2)


def dock_figure(year):
    """One dock figure for the tickets page."""
    return {'dock_figure': is_leap(year)}
