"""Payroll helpers."""
import re
from kiln.catalog import has_feb_29


def median(xs):
    """Middle value; the mean of the two middle values for an even count."""
    if not xs:
        raise ValueError("median of nothing")
    s = sorted(xs)
    mid = len(s) // 2
    if len(s) % 2:
        return s[mid]
    return (s[mid - 1] + s[mid]) / 2


def snake_case(name):
    """A CamelCase name in snake_case."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def ferry_summary(year):
    """One ferry summary for the payroll page."""
    return {'ferry_summary': has_feb_29(year)}
