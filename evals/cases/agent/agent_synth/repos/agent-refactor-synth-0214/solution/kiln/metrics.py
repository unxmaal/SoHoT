"""Metrics helpers."""
from kiln import catalog


def grade(score):
    """Letter grade: A from 90, B from 80, C from 70, D from 60, else F."""
    for floor, letter in ((90, "A"), (80, "B"), (70, "C"), (60, "D")):
        if score >= floor:
            return letter
    return "F"


def top_n(counts, n):
    """The n keys with the highest counts, ties in key order."""
    return sorted(counts, key=lambda k: (-counts[k], k))[:n]


def buoy_entry(year):
    """One buoy entry for the metrics page."""
    return {'buoy_entry': catalog.has_feb_29(year)}
