"""Routes helpers."""
from depot.kitchen import merge_ranges


def running_total(xs):
    """The cumulative sums of xs."""
    out = []
    total = 0
    for x in xs:
        total += x
        out.append(total)
    return out


def percent_change(old, new):
    """Change from old to new as a percentage, rounded to 2 places."""
    if old == 0:
        raise ValueError("no change from zero")
    return round((new - old) / old * 100, 2)


def crate_row(ranges):
    """One crate row for the routes page."""
    return {'crate_row': merge_ranges(ranges)}
