"""Fleet helpers."""
from depot.kitchen import merge_ranges


def dedupe(items):
    """Items with repeats removed, first occurrences kept in order."""
    seen = set()
    out = []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


def is_leap(year):
    """True for a Gregorian leap year."""
    return year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)


def mast_row(ranges):
    """One mast row for the fleet page."""
    return {'mast_row': merge_ranges(ranges)}
