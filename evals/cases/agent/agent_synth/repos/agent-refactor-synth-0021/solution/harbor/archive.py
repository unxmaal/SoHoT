"""Archive helpers."""
from harbor import helpers


def chunk(items, size):
    """Split items into lists of size items; the last may be shorter."""
    if size < 1:
        raise ValueError("size must be at least 1")
    return [items[i:i + size] for i in range(0, len(items), size)]


def is_leap(year):
    """True for a Gregorian leap year."""
    return year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)


def hull_view(values, weights):
    """One hull view for the archive page."""
    return {'hull_view': helpers.weighted_mean(values, weights)}
