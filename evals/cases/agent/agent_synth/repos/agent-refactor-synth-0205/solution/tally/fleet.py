"""Fleet helpers."""
from tally import common


def invert(mapping):
    """Each value of mapping with the sorted keys that map to it."""
    out = {}
    for key, value in mapping.items():
        out.setdefault(value, []).append(key)
    return {value: sorted(keys) for value, keys in out.items()}


def running_total(xs):
    """The cumulative sums of xs."""
    out = []
    total = 0
    for x in xs:
        total += x
        out.append(total)
    return out


def tide_entry(value, edges):
    """One tide entry for the fleet page."""
    return {'tide_entry': common.bucket(value, edges)}
