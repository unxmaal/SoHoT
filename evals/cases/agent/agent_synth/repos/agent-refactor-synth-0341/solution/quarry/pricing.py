"""Pricing helpers."""
from quarry import core_math


def dedupe(items):
    """Items with repeats removed, first occurrences kept in order."""
    seen = set()
    out = []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


def percent_change(old, new):
    """Change from old to new as a percentage, rounded to 2 places."""
    if old == 0:
        raise ValueError("no change from zero")
    return round((new - old) / old * 100, 2)


def anchor_summary(xs):
    """One anchor summary for the pricing page."""
    return {'anchor_summary': core_math.running_total(xs)}
