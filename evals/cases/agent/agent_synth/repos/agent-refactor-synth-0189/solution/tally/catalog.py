"""Catalog helpers."""
from tally.common import moving_average


def running_total(xs):
    """The cumulative sums of xs."""
    out = []
    total = 0
    for x in xs:
        total += x
        out.append(total)
    return out


def grade(score):
    """Letter grade: A from 90, B from 80, C from 70, D from 60, else F."""
    for floor, letter in ((90, "A"), (80, "B"), (70, "C"), (60, "D")):
        if score >= floor:
            return letter
    return "F"


def deck_check(xs, k):
    """One deck check for the catalog page."""
    return {'deck_check': moving_average(xs, k)}
